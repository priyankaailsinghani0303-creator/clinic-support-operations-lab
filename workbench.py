"""Run: streamlit run workbench.py"""
import csv
import io
import json
import tempfile
from pathlib import Path
from datetime import datetime, timedelta, timezone

import streamlit as st
from workbench_core import Workbench, SCENARIOS, TARGETS, clock, utcnow, parse

st.set_page_config(page_title='Clinic Support Workbench', page_icon='🩺', layout='wide')
st.title('Clinic Support Workbench')
st.caption('Interactive synthetic support cases • Investigation → verification → handoff → resolution')
st.info('Practice environment only. Use fictional names and text. Every result is generated by a deterministic simulator; no clinic, payment processor or SMS provider is connected.')
if 'practice_db' not in st.session_state:
    st.session_state.practice_db = str(Path(tempfile.mkdtemp(prefix='clinic-practice-')) / 'practice.sqlite')
wb = Workbench(st.session_state.practice_db)
st.sidebar.header('Your practice workspace')
st.sidebar.caption('Records survive reruns in this browser session. A new session or host restart may lose them. Download reports before leaving. This is not durable shared storage.')
with st.sidebar.form('new_case'):
    scenario = st.selectbox('Scenario', list(SCENARIOS))
    priority = st.selectbox('Practice priority', list(TARGETS), index=2)
    st.caption('Illustrative targets only; elapsed UTC time, no pauses. Choose priority after reviewing impact in a real workflow.')
    if st.form_submit_button('Create synthetic ticket'):
        wb.create(scenario, priority)
        st.rerun()
if st.sidebar.button('Refresh deadlines'):
    st.rerun()

tickets = wb.tickets()
now = utcnow()
if not tickets:
    st.write('Create a synthetic ticket in the sidebar to begin. Complete the evidence checks, record a response and verify the workflow before closing it.')
    st.stop()
rows = []
for t in tickets:
    response_target, resolution_target = TARGETS[t['priority']]
    rows.append({'Ticket': f"S{t['id']:03d}", 'Scenario': t['scenario'], 'Status': t['status'],
                 'Owner': t['owner'] or 'Unassigned',
                 'First response': clock(t['created'], t['responded'], response_target, now)['state'],
                 'Resolution': clock(t['created'], t['resolved'], resolution_target, now)['state'],
                 'Update due': t['next_update'] or '—',
                 'Follow-up overdue': bool(t['next_update'] and parse(t['next_update']) < parse(now))})
a,b,c = st.columns(3)
a.metric('Open / escalated', sum(t['status'] != 'Resolved' for t in tickets))
b.metric('Unassigned', sum(not t['owner'] and t['status'] != 'Resolved' for t in tickets))
c.metric('Verified and resolved', sum(t['status'] == 'Resolved' for t in tickets))
queue, investigation, review = st.tabs(['Queue & deadlines', 'Investigate a ticket', 'Patterns & handoff'])
with queue:
    st.dataframe(rows, hide_index=True, width='stretch')
    st.caption('Pending/At risk/Overdue use the current clock at page refresh. Met/Breached use recorded completion. Reopened resolution clocks run from original creation; prior closures remain in history.')
    out = io.StringIO()
    writer = csv.DictWriter(out, fieldnames=list(rows[0]))
    writer.writeheader()
    writer.writerows(rows)
    st.download_button('Export queue CSV', out.getvalue(), 'synthetic-support-queue.csv', 'text/csv')
with investigation:
    ticket_id = st.selectbox('Ticket', [t['id'] for t in tickets], format_func=lambda v: f'S{v:03d}')
    t = wb.get(ticket_id)
    s = SCENARIOS[t['scenario']]
    st.subheader(f"{t['scenario']} · {t['status']}")
    st.write('**Reported:**', s['report'])
    st.write('**Expected:**', s['expected'])
    st.write('**Recorded findings:**', json.loads(t['findings']) or 'None yet')
    def act(action, **kwargs):
        try:
            wb.act(ticket_id, action, **kwargs)
        except ValueError as exc:
            st.error(str(exc))
        else:
            st.rerun()
    with st.form(f'owner_{ticket_id}'):
        owner = st.text_input('Fictional support owner', value=t['owner'])
        minutes = st.number_input('Next update in minutes', 1, 1440, 30)
        if st.form_submit_button('Accept ownership'):
            act('Accept ownership', owner=owner, deadline=(datetime.now(timezone.utc)+timedelta(minutes=int(minutes))).isoformat())
    st.markdown('**1. Gather evidence**')
    for check in s['checks']:
        if st.button(check, key=f'{ticket_id}_{check}'):
            act(check)
    st.markdown('**2. Apply and verify the simulated action**')
    if st.button(s['fix'], key=f'fix_{ticket_id}'):
        act(s['fix'])
    if st.button('Verify workflow', key=f'verify_{ticket_id}'):
        act('Verify workflow')
    if t['verified']:
        st.success(s['verification'])
    st.markdown('**3. Communicate and close or escalate**')
    with st.form(f'communication_{ticket_id}'):
        action = st.selectbox('Record type', ['Record response', 'Record escalation', 'Record simulated customer confirmation', 'Resolve', 'Reopen'])
        note = st.text_area('Fictional response / evidence / summary', help='For escalation include receiving team, findings, unknowns, question and next action. Confirmation is a role-play entry, not an independent customer statement.')
        if st.form_submit_button('Record action'):
            act(action, text=note)
    st.caption('Closure requires an owner, first response, simulator verification, a role-play customer confirmation and a written summary.')
    st.markdown('**Customer guidance**')
    st.write(s['article'])
    st.markdown('**Timestamped event history**')
    st.dataframe(wb.events(ticket_id), hide_index=True, width='stretch')
    st.download_button('Download investigation & handoff', wb.report(ticket_id), f'synthetic-S{ticket_id:03d}.md', 'text/markdown')
with review:
    st.write('**Repeated symptoms to review**')
    counts = {name: sum(t['scenario'] == name and t['status'] != 'Resolved' for t in tickets) for name in SCENARIOS}
    st.dataframe([{'Scenario': k, 'Open reports': v} for k,v in counts.items()], hide_index=True)
    st.caption('Counts cover this synthetic workspace only. Similar reports are a review signal; they do not establish an outage or shared cause. Compare time window, scope, configuration and delivery/processor evidence.')
    st.write('**Handoff checklist:** Confirm one owner, evidence collected, unknowns, next action and update deadline. Escalation retains the support owner; no specialist acceptance is simulated.')
    combined = '\n\n---\n\n'.join(wb.report(t['id']) for t in tickets)
    st.download_button('Export complete shift handoff', combined, 'synthetic-shift-handoff.md', 'text/markdown')
